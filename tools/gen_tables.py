#!/usr/bin/env python3
"""Writes src/gs_tables.c: the synth's fixed-point tables, so the library
needs no floating point at run time. --check fails when the file differs.
MIT, Copyright (c) 2026 AmiCradle Team."""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "gs_tables.c")


def rows(vals, per=12):
    out = []
    for i in range(0, len(vals), per):
        out.append("\t" + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def build():
    # 2^(c/1200) for c in 0..1199, Q16 (65536..131071)
    exp2 = [round(65536 * 2 ** (c / 1200.0)) for c in range(1200)]
    # 10^(-cB/200) for cB 0..1440, Q15 (32767 at 0)
    gain = [min(32767, round(32768 * 10 ** (-c / 200.0))) for c in range(1441)]
    gain[1440] = 0
    # the SF2 concave curve for velocity, CC7 and CC11: 400*log10(127/x) cB
    curve = [1440] + [min(1440, round(400 * math.log10(127.0 / x))) for x in range(1, 128)]
    # constant-power pan: sin(pi/2 * i/128), Q15, i 0..128
    pan = [min(32767, round(32768 * math.sin(math.pi / 2 * i / 128.0))) for i in range(129)]
    src = []
    src.append("/* Generated by tools/gen_tables.py; do not edit.")
    src.append(" * MIT, Copyright (c) 2026 AmiCradle Team. */")
    src.append('#include "gs_tables.h"')
    src.append("")
    src.append("/* 2^(c/1200), Q16, c 0..1199 */")
    src.append("const unsigned long gs_exp2_q16[1200] = {")
    src.append(rows(exp2))
    src.append("};")
    src.append("")
    src.append("/* 10^(-cB/200), Q15, cB 0..1440 */")
    src.append("const unsigned short gs_cb_gain_q15[1441] = {")
    src.append(rows(gain))
    src.append("};")
    src.append("")
    src.append("/* 400*log10(127/x) cB, x 0..127 (the SF2 concave curve) */")
    src.append("const unsigned short gs_curve_cb[128] = {")
    src.append(rows(curve))
    src.append("};")
    src.append("")
    src.append("/* sin(pi/2 * i/128), Q15, i 0..128 (constant-power pan) */")
    src.append("const unsigned short gs_pan_q15[129] = {")
    src.append(rows(pan))
    src.append("};")
    return "\n".join(src) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        with open(OUT) as f:
            if f.read() != text:
                print("src/gs_tables.c is out of date: run tools/gen_tables.py")
                return 1
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
